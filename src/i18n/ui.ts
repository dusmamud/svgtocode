/** Get the dictionary for a locale (fallback: English). */
export function getDict(locale: string): Dict {
  switch (locale) {
    case 'hi': return hi;
    case 'es': return es;
    case 'pt': return pt;
    case 'fr': return fr;
    case 'de': return de;
    case 'id': return id;
    case 'ja': return ja;
    default: return en;
  }
}

/** Check whether a locale has a full native translation. */
export function isFullyTranslated(locale: string): boolean {
  return (FULLY_TRANSLATED as readonly string[]).includes(locale);
}
